// Lists the FindSoftware record for each software value, so a /software/<value>/ page links only to records that exist.
// Usage: node scripts/findsoftware-pages.mjs [path to a built FindSoftware dist/]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parse, stringify } from 'yaml';

const dist = process.argv[2] ?? '../findsoftware/dist';
if (!existsSync(dist)) throw new Error(`No FindSoftware build at ${dist}: run pnpm build there first.`);

// Listed records only: a record beside the register or hidden is no page to send a reader to.
const { software } = JSON.parse(readFileSync(`${dist}/software.json`, 'utf8'));
const differing = parse(readFileSync(`${dist}/../src/data/findhost-ids.yml`, 'utf8')) ?? {};
const values = new Set(
  parse(readFileSync('src/data/fields.yml', 'utf8'))
    .find((field) => field.id === 'software')
    .values.map((value) => value.id),
);

const records = {};
for (const record of software) {
  const value = differing[record.id] ?? record.id;
  if (values.has(value)) records[value] = record.href;
}
const sorted = Object.fromEntries(Object.entries(records).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  'src/data/findsoftware.yml',
  `# Generated by scripts/findsoftware-pages.mjs from a FindSoftware build: software value → record path.\n${stringify(sorted)}`,
);
console.log(`${Object.keys(sorted).length} of ${values.size} software values have a FindSoftware record`);
